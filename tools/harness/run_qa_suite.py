"""Grounded QA suite (P3.10): transcribe each fixture once (real ASR), ask each planted fact's question 5 s after it
was said (later segments excluded), check must_contain. Writes docs/evidence/qa.md + docs/evidence/raw/qa.json.
Targets (HANDOVER §15 A2): ≥ 8/10 per English fixture on the phone tier. Run: make harness
"""

import json
import platform
import statistics
import subprocess
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FIX = ROOT / "Tests/Fixtures"
CACHE = ROOT / ".build/qa"
EVIDENCE = ROOT / "docs/evidence"
MODELS = {  # label → EarCLI arguments
    "Gemma 4 E2B Q4_0 (phone default, ADR-014)": ["--model", "llm/gemma-4-E2B-it-Q4_0.gguf"],
    "Qwen3-1.7B Q4_K_M (low-memory option)": ["--model", "llm/Qwen3-1.7B-Q4_K_M.gguf"],
    "Qwen3-0.6B Q8_0 (tiny, sanity)": ["--answerer", "tiny"],
}


def bin_path() -> Path:
    subprocess.run(["swift", "build", "-c", "release", "--product", "EarCLI"], cwd=ROOT, check=True)
    out = subprocess.run(["swift", "build", "-c", "release", "--show-bin-path"], cwd=ROOT, check=True,
                         capture_output=True, text=True).stdout.strip()  # fmt: skip
    return Path(out) / "EarCLI"


def transcript(cli: Path, name: str) -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    out = CACHE / f"{name}.jsonl"
    wav = FIX / f"{name}.wav"
    if not out.exists() or out.stat().st_mtime < wav.stat().st_mtime:
        out.write_text(
            subprocess.run(
                [str(cli), "transcribe", str(wav)], check=True, capture_output=True, text=True
            ).stdout
        )
    return out


def main() -> int:
    cli = bin_path()
    names = sorted(p.stem for p in (FIX / "scripts").glob("*.txt"))
    rows, raw = [], []
    for name in names:
        tr = transcript(cli, name)
        for label, extra in MODELS.items():
            cmd = [
                str(cli),
                "qa",
                "--fixture",
                name,
                "--fixtures",
                str(FIX),
                "--transcript",
                str(tr),
                *extra,
            ]
            res = [
                json.loads(line)
                for line in subprocess.run(
                    cmd, check=True, capture_output=True, text=True
                ).stdout.splitlines()
            ]
            ft = [r["firstTokenSeconds"] for r in res]
            rows.append({"fixture": name, "model": label, "correct": sum(r["correct"] for r in res), "n": len(res),
                         "ft_p50": statistics.median(ft), "ft_p95": sorted(ft)[int(0.95 * (len(ft) - 1))],
                         "total_p50": statistics.median(r["totalSeconds"] for r in res)})  # fmt: skip
            raw += [{"fixture": name, "model": label, **r} for r in res]
            print(
                f"{name:14} {label:44} {rows[-1]['correct']}/{rows[-1]['n']}  first token p50 {rows[-1]['ft_p50']:.2f} s",
                flush=True,
            )
    (EVIDENCE / "raw").mkdir(parents=True, exist_ok=True)
    (EVIDENCE / "raw/qa.json").write_text(json.dumps(raw, indent=2) + "\n")
    lines = [
        "# Grounded QA evidence (A2)",
        "",
        f"Generated by `tools/harness/run_qa_suite.py` on {date.today()} — macOS {platform.mac_ver()[0]}, {platform.machine()} "
        "(Metal). Transcripts come from the real ASR pipeline (Zipformer + Silero, docs/evidence/asr.md); each planted "
        "fact's question is asked 5 s after the fact, greedy decoding, phone-tier prompt (2,000-token budget, ≤ 80 words). "
        "Correct = the answer contains one of the fact's `must_contain` strings. Latency is on the Mac, not the phone "
        "(device numbers need LLMBench, ADR-010).",
        "",
        "| Fixture | Model | Correct | Target | First token p50 / p95 | Answer p50 |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        target = "sanity only" if "tiny" in r["model"] else "≥ 8/10"
        lines.append(
            f"| {r['fixture']} | {r['model']} | {r['correct']}/{r['n']} | {target} | {r['ft_p50']:.2f} / {r['ft_p95']:.2f} s | {r['total_p50']:.2f} s |"
        )
    misses = [r for r in raw if not r["correct"] and "tiny" not in r["model"]]
    lines += ["", "## Misses (phone-tier models)", ""]
    lines += [
        f"- {m['fixture']} / {m['model']}: expected {m['mustContain']} — “{m['answer'][:140]}”"
        for m in misses
    ]
    (EVIDENCE / "qa.md").write_text("\n".join(lines) + "\n")
    print("wrote docs/evidence/qa.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
