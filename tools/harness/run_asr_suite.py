"""ASR suite (P2.9): transcribe every fixture variant and the LibriSpeech sample with EarCLI, write
docs/evidence/asr.md and docs/evidence/raw/asr.json.  Run: make harness (or python3 tools/harness/run_asr_suite.py)
Thresholds: HANDOVER §15 A1, sherpa rows (Apple engine dropped, ADR-008).
"""

import json
import platform
import subprocess
import sys
import time
from datetime import date
from pathlib import Path

import wer

ROOT = Path(__file__).resolve().parents[2]
FIX = ROOT / "Tests/Fixtures"
EVIDENCE = ROOT / "docs/evidence"
THRESHOLDS = {"clean": 0.15, "snr20": 0.20, "snr10": 0.30, "librispeech": 0.17}


def earcli() -> Path:
    subprocess.run(["swift", "build", "-c", "release", "--product", "EarCLI"], cwd=ROOT, check=True)
    out = subprocess.run(["swift", "build", "-c", "release", "--show-bin-path"], cwd=ROOT, check=True,
                         capture_output=True, text=True).stdout.strip()  # fmt: skip
    return Path(out) / "EarCLI"


def transcribe(cli: Path, wav: Path) -> tuple[str, float]:
    t0 = time.monotonic()
    out = subprocess.run(
        [str(cli), "transcribe", str(wav)], check=True, capture_output=True, text=True
    ).stdout
    text = " ".join(json.loads(line)["text"] for line in out.splitlines() if line.strip())
    return text, time.monotonic() - t0


def main() -> int:
    cli = earcli()
    rows = []
    for script in sorted((FIX / "scripts").glob("*.txt")):
        name = script.stem
        for variant, suffix in (("clean", ""), ("snr20", "_snr20"), ("snr10", "_snr10")):
            wav = FIX / f"{name}{suffix}.wav"
            hyp, secs = transcribe(cli, wav)
            audio = json.loads((FIX / f"{name}.timeline.json").read_text())[-1]["t1"]
            rows.append({"set": name, "variant": variant, "wer": wer.wer(script.read_text(), hyp),
                         "rtf": secs / audio, "threshold": THRESHOLDS[variant]})  # fmt: skip
            print(
                f"{name:16} {variant:6} WER {rows[-1]['wer'] * 100:5.1f} %  RTF {rows[-1]['rtf']:.3f}",
                flush=True,
            )
    refs = json.loads((FIX / "librispeech_sample/refs.json").read_text())
    ref_all, hyp_all, secs_all = [], [], 0.0
    for r in refs:
        hyp, secs = transcribe(cli, FIX / "librispeech_sample" / r["wav"])
        ref_all.append(r["text"])
        hyp_all.append(hyp)
        secs_all += secs
    rows.append({"set": "librispeech_sample (20 utts)", "variant": "librispeech",
                 "wer": wer.wer(" ".join(ref_all), " ".join(hyp_all)), "rtf": None,
                 "threshold": THRESHOLDS["librispeech"]})  # fmt: skip
    print(f"librispeech WER {rows[-1]['wer'] * 100:.1f} %")

    (EVIDENCE / "raw").mkdir(parents=True, exist_ok=True)
    (EVIDENCE / "raw/asr.json").write_text(json.dumps(rows, indent=2) + "\n")
    lines = [
        "# ASR evidence (A1)",
        "",
        f"Generated by `tools/harness/run_asr_suite.py` on {date.today()} — {platform.mac_ver()[0]} macOS, "
        f"{platform.machine()}. Engine: sherpa-onnx streaming Zipformer en 2023-06-26 int8 + Silero VAD v5 "
        "(models.lock.json). Apple SpeechAnalyzer not measured (ADR-008). RTF = wall time / audio time, "
        "4 threads, faster than real time.",
        "",
        "| Set | Variant | WER | Threshold | RTF | Pass |",
        "|---|---|---|---|---|---|",
    ]
    for r in rows:
        rtf = f"{r['rtf']:.3f}" if r["rtf"] is not None else "—"
        ok = "yes" if r["wer"] <= r["threshold"] else "**no**"
        lines.append(
            f"| {r['set']} | {r['variant']} | {r['wer'] * 100:.1f} % | ≤ {r['threshold'] * 100:.0f} % | {rtf} | {ok} |"
        )
    failed = [r for r in rows if r["wer"] > r["threshold"]]
    lines += ["", f"{len(rows) - len(failed)}/{len(rows)} rows within threshold.", ""]
    (EVIDENCE / "asr.md").write_text("\n".join(lines))
    print(f"wrote docs/evidence/asr.md ({len(failed)} rows over threshold)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
